/** Turns an icon definition into merged horizontal runs: [x, y, width, colour]. */
export function iconRuns(def: PixelIconDef): [number, number, number, string][] {
  const runs: [number, number, number, string][] = []
  def.rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      let w = 1
      while (x + w < row.length && row[x + w] === ch) w++
      const color = ch === '.' ? undefined : def.palette[ch]
      if (color) runs.push([x, y, w, color])
      x += w
    }
  })
  return runs
}
